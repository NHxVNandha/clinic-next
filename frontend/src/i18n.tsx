export type TranslationKey = keyof typeof translations.id

const LanguageContext = createContext<{ language: Language; toggleLanguage: () => void; t: (key: TranslationKey) => string } | null>(null)

function readLanguage(): Language {
  const stored = localStorage.getItem(STORAGE_KEY)
  return stored === 'en' || stored === 'id' ? stored : 'id'
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => readLanguage())

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language)
    document.documentElement.lang = language
  }, [language])

  const value = useMemo(() => ({
    language,
    toggleLanguage: () => setLanguage((current) => (current === 'id' ? 'en' : 'id')),
    t: (key: TranslationKey) => translations[language][key] ?? translations.id[key] ?? key,
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useT() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useT must be used within LanguageProvider')
  return context
}
